//! Purchases and discounts: what a project costs beyond time.
//!
//! Gryzzly gates both behind its budget offer. On a plan without it, every call
//! here comes back as `no_permission`, which is upstream policy rather than a
//! configuration mistake.

use rmcp::{ErrorData as McpError, Json, handler::server::wrapper::Parameters};
use serde::{Deserialize, Serialize};

use crate::{
    error::Error,
    model::{Discount, Page, Purchase},
    server::GryzzlyServer,
    tools::{Body, Deleted, Listing, PageArgs, ok, opt_date, require_confirmation},
};

/// How a purchase weighs on the budget.
#[derive(Debug, Clone, Copy, Deserialize, Serialize, schemars::JsonSchema)]
#[serde(rename_all = "lowercase")]
pub enum BillingPolicy {
    /// Counted in the budget.
    Add,
    /// Recorded but not counted.
    Ignore,
}

impl BillingPolicy {
    fn as_str(self) -> &'static str {
        match self {
            Self::Add => "add",
            Self::Ignore => "ignore",
        }
    }
}

/// Arguments of `list_purchases` and `list_discounts`.
#[derive(Debug, Clone, Default, Deserialize, schemars::JsonSchema)]
pub struct ListChargesArgs {
    /// Keep only charges of these projects, by name, code or id.
    pub projects: Option<Vec<String>>,
    /// Keep only charges of these tasks, by name or id.
    pub tasks: Option<Vec<String>>,
    /// Pagination.
    #[serde(flatten)]
    pub page: PageArgs,
}

/// Arguments of a tool that reads or deletes one charge.
#[derive(Debug, Clone, Deserialize, schemars::JsonSchema)]
pub struct ChargeRefArgs {
    /// The identifier.
    pub id: String,
    /// Must be `true` to delete. Ignored when reading.
    pub confirm: Option<bool>,
}

/// Arguments of `create_purchase`.
#[derive(Debug, Clone, Deserialize, schemars::JsonSchema)]
pub struct CreatePurchaseArgs {
    /// What was bought.
    pub name: String,
    /// The project it is charged to, by name, code or id. One of project or task.
    pub project: Option<String>,
    /// The task it is charged to, by name or id. One of project or task.
    pub task: Option<String>,
    /// What it cost.
    pub paid_price: Option<f64>,
    /// When it was paid.
    pub paid_at: Option<String>,
    /// What it is billed for.
    pub billed_price: Option<f64>,
    /// When it was billed.
    pub billed_at: Option<String>,
    /// Whether it counts in the budget. Defaults to `add`.
    pub billing_policy: Option<BillingPolicy>,
}

/// Arguments of `update_purchase`.
#[derive(Debug, Clone, Deserialize, schemars::JsonSchema)]
pub struct UpdatePurchaseArgs {
    /// The purchase's identifier.
    pub id: String,
    /// A new name.
    pub name: Option<String>,
    /// A new paid price.
    pub paid_price: Option<f64>,
    /// A new paid date.
    pub paid_at: Option<String>,
    /// A new billed price.
    pub billed_price: Option<f64>,
    /// A new billed date.
    pub billed_at: Option<String>,
    /// A new billing policy.
    pub billing_policy: Option<BillingPolicy>,
}

/// Arguments of `create_discount`.
#[derive(Debug, Clone, Deserialize, schemars::JsonSchema)]
pub struct CreateDiscountArgs {
    /// The discount's name.
    pub name: String,
    /// How much is taken off.
    pub amount: Option<f64>,
    /// The project it applies to, by name, code or id. One of project or task.
    pub project: Option<String>,
    /// The task it applies to, by name or id. One of project or task.
    pub task: Option<String>,
}

/// Arguments of `update_discount`.
#[derive(Debug, Clone, Deserialize, schemars::JsonSchema)]
pub struct UpdateDiscountArgs {
    /// The discount's identifier.
    pub id: String,
    /// A new name.
    pub name: Option<String>,
    /// A new amount.
    pub amount: Option<f64>,
}

#[allow(missing_docs, reason = "the router function is generated by the macro")]
#[rmcp::tool_router(router = budget_router, vis = "pub")]
impl GryzzlyServer {
    /// Change an existing discount's name or amount, by its identifier. Only
    /// the fields you pass are sent. Use create_discount for a new one and
    /// delete_discount to remove one; the project or task a discount applies to
    /// cannot be moved. Requires Gryzzly's budget offer.
    #[rmcp::tool(annotations(
        title = "List purchases",
        read_only_hint = true,
        open_world_hint = true
    ))]
    pub async fn list_purchases(
        &self,
        Parameters(args): Parameters<ListChargesArgs>,
    ) -> std::result::Result<Json<Listing<Purchase>>, McpError> {
        let body = Body::new()
            .paged(&args.page)
            .set_list("project_ids", self.project_ids(args.projects).await?)
            .set_list("task_ids", self.task_ids(args.tasks).await?)
            .build();
        let page: Page<Purchase> = self.client().list("purchases.list", &body).await?;
        ok(Listing::new(page.count, page.data))
    }

    /// Read one purchase by identifier, with its amounts and its dates.
    #[rmcp::tool(annotations(
        title = "Get a purchase",
        read_only_hint = true,
        open_world_hint = true
    ))]
    pub async fn get_purchase(
        &self,
        Parameters(args): Parameters<ChargeRefArgs>,
    ) -> std::result::Result<Json<Purchase>, McpError> {
        let purchase: Purchase = self
            .client()
            .call("purchases.get", &Body::new().set("id", args.id).build())
            .await?;
        ok(purchase)
    }

    /// Record a purchase against a project or a task.
    #[rmcp::tool(annotations(
        title = "Create a purchase",
        read_only_hint = false,
        destructive_hint = false,
        idempotent_hint = false,
        open_world_hint = true
    ))]
    pub async fn create_purchase(
        &self,
        Parameters(args): Parameters<CreatePurchaseArgs>,
    ) -> std::result::Result<Json<Purchase>, McpError> {
        let (project_id, task_id) = self
            .charge_target(args.project.as_deref(), args.task.as_deref())
            .await?;
        let body = Body::new()
            .set("name", args.name)
            .set_opt("project_id", project_id)
            .set_opt("task_id", task_id)
            .set_opt("paid_price", args.paid_price)
            .set_opt("paid_at", opt_date(args.paid_at.as_deref())?)
            .set_opt("billed_price", args.billed_price)
            .set_opt("billed_at", opt_date(args.billed_at.as_deref())?)
            .set_opt(
                "billing_policy",
                args.billing_policy.map(BillingPolicy::as_str),
            )
            .build();
        let purchase: Purchase = self.client().call("purchases.create", &body).await?;
        ok(purchase)
    }

    /// Change a purchase: its name, its prices, its dates, its billing policy.
    #[rmcp::tool(annotations(
        title = "Update a purchase",
        read_only_hint = false,
        destructive_hint = false,
        idempotent_hint = true,
        open_world_hint = true
    ))]
    pub async fn update_purchase(
        &self,
        Parameters(args): Parameters<UpdatePurchaseArgs>,
    ) -> std::result::Result<Json<Purchase>, McpError> {
        let body = Body::new()
            .set("id", args.id)
            .set_opt("name", args.name)
            .set_opt("paid_price", args.paid_price)
            .set_opt("paid_at", opt_date(args.paid_at.as_deref())?)
            .set_opt("billed_price", args.billed_price)
            .set_opt("billed_at", opt_date(args.billed_at.as_deref())?)
            .set_opt(
                "billing_policy",
                args.billing_policy.map(BillingPolicy::as_str),
            )
            .build();
        let purchase: Purchase = self.client().call("purchases.update", &body).await?;
        ok(purchase)
    }

    /// Delete a purchase, which removes its amount from the project's budget.
    #[rmcp::tool(annotations(
        title = "Delete a purchase",
        read_only_hint = false,
        destructive_hint = true,
        idempotent_hint = true,
        open_world_hint = true
    ))]
    pub async fn delete_purchase(
        &self,
        Parameters(args): Parameters<ChargeRefArgs>,
    ) -> std::result::Result<Json<Deleted>, McpError> {
        require_confirmation(args.confirm.unwrap_or(false), "this purchase")?;
        let _: serde_json::Value = self
            .client()
            .call(
                "purchases.delete",
                &Body::new().set("id", args.id.clone()).build(),
            )
            .await?;
        ok(Deleted::new("purchase", args.id))
    }

    /// List discounts applied to projects or tasks, with their amounts.
    #[rmcp::tool(annotations(
        title = "List discounts",
        read_only_hint = true,
        open_world_hint = true
    ))]
    pub async fn list_discounts(
        &self,
        Parameters(args): Parameters<ListChargesArgs>,
    ) -> std::result::Result<Json<Listing<Discount>>, McpError> {
        let body = Body::new()
            .paged(&args.page)
            .set_list("project_ids", self.project_ids(args.projects).await?)
            .set_list("task_ids", self.task_ids(args.tasks).await?)
            .build();
        let page: Page<Discount> = self.client().list("discounts.list", &body).await?;
        ok(Listing::new(page.count, page.data))
    }

    /// Read one discount by identifier, with its amounts and its dates.
    #[rmcp::tool(annotations(
        title = "Get a discount",
        read_only_hint = true,
        open_world_hint = true
    ))]
    pub async fn get_discount(
        &self,
        Parameters(args): Parameters<ChargeRefArgs>,
    ) -> std::result::Result<Json<Discount>, McpError> {
        let discount: Discount = self
            .client()
            .call("discounts.get", &Body::new().set("id", args.id).build())
            .await?;
        ok(discount)
    }

    /// Apply a discount to a project or a task.
    #[rmcp::tool(annotations(
        title = "Create a discount",
        read_only_hint = false,
        destructive_hint = false,
        idempotent_hint = false,
        open_world_hint = true
    ))]
    pub async fn create_discount(
        &self,
        Parameters(args): Parameters<CreateDiscountArgs>,
    ) -> std::result::Result<Json<Discount>, McpError> {
        let (project_id, task_id) = self
            .charge_target(args.project.as_deref(), args.task.as_deref())
            .await?;
        let body = Body::new()
            .set("name", args.name)
            .set_opt("amount", args.amount)
            .set_opt("project_id", project_id)
            .set_opt("task_id", task_id)
            .build();
        let discount: Discount = self.client().call("discounts.create", &body).await?;
        ok(discount)
    }

    /// Change a discount's name or amount.
    #[rmcp::tool(annotations(
        title = "Update a discount",
        read_only_hint = false,
        destructive_hint = false,
        idempotent_hint = true,
        open_world_hint = true
    ))]
    pub async fn update_discount(
        &self,
        Parameters(args): Parameters<UpdateDiscountArgs>,
    ) -> std::result::Result<Json<Discount>, McpError> {
        let body = Body::new()
            .set("id", args.id)
            .set_opt("name", args.name)
            .set_opt("amount", args.amount)
            .build();
        let discount: Discount = self.client().call("discounts.update", &body).await?;
        ok(discount)
    }

    /// Delete a discount, which puts its amount back into the project's budget.
    #[rmcp::tool(annotations(
        title = "Delete a discount",
        read_only_hint = false,
        destructive_hint = true,
        idempotent_hint = true,
        open_world_hint = true
    ))]
    pub async fn delete_discount(
        &self,
        Parameters(args): Parameters<ChargeRefArgs>,
    ) -> std::result::Result<Json<Deleted>, McpError> {
        require_confirmation(args.confirm.unwrap_or(false), "this discount")?;
        let _: serde_json::Value = self
            .client()
            .call(
                "discounts.delete",
                &Body::new().set("id", args.id.clone()).build(),
            )
            .await?;
        ok(Deleted::new("discount", args.id))
    }
}

impl GryzzlyServer {
    /// Resolve a list of projects to identifiers.
    async fn project_ids(
        &self,
        needles: Option<Vec<String>>,
    ) -> std::result::Result<Option<Vec<String>>, Error> {
        let Some(needles) = needles else {
            return Ok(None);
        };
        let mut ids = Vec::with_capacity(needles.len());
        for needle in &needles {
            ids.push(self.directory().project(needle).await?.id);
        }
        Ok(Some(ids))
    }

    /// Resolve a list of tasks to identifiers.
    async fn task_ids(
        &self,
        needles: Option<Vec<String>>,
    ) -> std::result::Result<Option<Vec<String>>, Error> {
        let Some(needles) = needles else {
            return Ok(None);
        };
        let mut ids = Vec::with_capacity(needles.len());
        for needle in &needles {
            ids.push(self.directory().task(needle, None).await?.id);
        }
        Ok(Some(ids))
    }

    /// A purchase or a discount hangs on a project or on a task, never on both
    /// and never on neither.
    async fn charge_target(
        &self,
        project: Option<&str>,
        task: Option<&str>,
    ) -> std::result::Result<(Option<String>, Option<String>), Error> {
        match (project, task) {
            (Some(project), None) => Ok((Some(self.directory().project(project).await?.id), None)),
            (None, Some(task)) => Ok((None, Some(self.directory().task(task, None).await?.id))),
            (Some(_), Some(_)) => Err(Error::invalid(
                "name a project or a task, not both: Gryzzly hangs the charge on one of them",
            )),
            (None, None) => Err(Error::invalid("name the project or the task to charge")),
        }
    }
}
