//! Leave periods: days off, half days, and the CSV import Gryzzly accepts for
//! them.

use rmcp::{ErrorData as McpError, Json, handler::server::wrapper::Parameters};
use serde::{Deserialize, Serialize};

use crate::{
    dates,
    error::Error,
    model::{ImportReport, LeavePeriod, Page},
    server::GryzzlyServer,
    tools::{Body, Deleted, Listing, PageArgs, date, ok, opt_date, require_confirmation},
};

/// How much of a day a leave covers at its edges.
#[derive(Debug, Clone, Copy, Deserialize, Serialize, schemars::JsonSchema)]
#[serde(rename_all = "lowercase")]
pub enum DayPart {
    /// The whole day.
    Full,
    /// The morning only.
    Am,
    /// The afternoon only.
    Pm,
}

impl DayPart {
    fn as_str(self) -> &'static str {
        match self {
            Self::Full => "full",
            Self::Am => "am",
            Self::Pm => "pm",
        }
    }
}

/// The file formats the leave importer accepts.
#[derive(Debug, Clone, Copy, Deserialize, Serialize, schemars::JsonSchema)]
#[serde(rename_all = "lowercase")]
pub enum ImportFormat {
    /// Comma-separated values, `text/csv`.
    Csv,
    /// An Excel workbook.
    Xlsx,
}

impl ImportFormat {
    fn content_type(self) -> &'static str {
        match self {
            Self::Csv => "text/csv",
            Self::Xlsx => "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet",
        }
    }
}

/// Arguments of `list_leave_periods`.
#[derive(Debug, Clone, Default, Deserialize, schemars::JsonSchema)]
pub struct ListLeavesArgs {
    /// A week: `this week`, `last week`, `2026-W38`, or a date inside it.
    pub week: Option<String>,
    /// First day of an explicit period.
    pub from: Option<String>,
    /// Last day of an explicit period.
    pub to: Option<String>,
    /// Whose leaves to read, by name, email or id. Defaults to everyone.
    pub users: Option<Vec<String>>,
    /// Pagination.
    #[serde(flatten)]
    pub page: PageArgs,
}

/// Arguments of `get_leave_period`.
#[derive(Debug, Clone, Deserialize, schemars::JsonSchema)]
pub struct LeaveRefArgs {
    /// The leave period's identifier.
    pub id: String,
    /// Must be `true` to delete. Ignored when reading.
    pub confirm: Option<bool>,
}

/// Arguments of `create_leave_period`.
#[derive(Debug, Clone, Deserialize, schemars::JsonSchema)]
pub struct CreateLeaveArgs {
    /// First day off.
    pub start_at: String,
    /// Last day off. Defaults to `start_at`, which is one day off.
    pub end_at: Option<String>,
    /// Whose leave it is, by name, email or id. Defaults to the current user.
    pub user: Option<String>,
    /// How much of the first day is off. Defaults to `full`.
    pub start_type: Option<DayPart>,
    /// How much of the last day is off. Defaults to `full`.
    pub end_type: Option<DayPart>,
    /// Why the person is away.
    pub description: Option<String>,
    /// Delete the declarations already made over those days. Defaults to false,
    /// which makes Gryzzly refuse the leave when time is already declared.
    pub delete_declarations: Option<bool>,
}

/// Arguments of `update_leave_period`.
#[derive(Debug, Clone, Deserialize, schemars::JsonSchema)]
pub struct UpdateLeaveArgs {
    /// The leave period's identifier.
    pub id: String,
    /// A new first day.
    pub start_at: Option<String>,
    /// A new last day.
    pub end_at: Option<String>,
    /// How much of the first day is off.
    pub start_type: Option<DayPart>,
    /// How much of the last day is off.
    pub end_type: Option<DayPart>,
    /// A new description.
    pub description: Option<String>,
    /// Delete the declarations already made over those days.
    pub delete_declarations: Option<bool>,
}

/// Arguments of `import_leave_periods`.
#[derive(Debug, Clone, Deserialize, schemars::JsonSchema)]
pub struct ImportLeavesArgs {
    /// The file's contents, for a CSV written inline.
    pub content: Option<String>,
    /// A path on the machine running this server, for a CSV or an XLSX.
    pub file_path: Option<String>,
    /// The format. Inferred from the file extension, or `csv` for inline content.
    pub format: Option<ImportFormat>,
}

#[allow(missing_docs, reason = "the router function is generated by the macro")]
#[rmcp::tool_router(router = leaves_router, vis = "pub")]
impl GryzzlyServer {
    /// List leave periods over a week or a period. Useful before logging time:
    /// Gryzzly refuses a declaration on a day already declared as leave.
    #[rmcp::tool(annotations(
        title = "List leave periods",
        read_only_hint = true,
        open_world_hint = true
    ))]
    pub async fn list_leave_periods(
        &self,
        Parameters(args): Parameters<ListLeavesArgs>,
    ) -> std::result::Result<Json<Listing<LeavePeriod>>, McpError> {
        let (from, to) = match args.week.as_deref() {
            Some(week) => dates::parse_week(week)?,
            None => match (args.from.as_deref(), args.to.as_deref()) {
                (Some(from), Some(to)) => (dates::parse_date(from)?, dates::parse_date(to)?),
                (Some(from), None) => {
                    let from = dates::parse_date(from)?;
                    (from, from + chrono::Duration::days(365))
                }
                (None, Some(to)) => {
                    let to = dates::parse_date(to)?;
                    (to - chrono::Duration::days(365), to)
                }
                (None, None) => dates::parse_week("this week")?,
            },
        };
        let body = Body::new()
            .paged(&args.page)
            .set("from", dates::api_date(from))
            .set("to", dates::api_date(to))
            .set_list("user_ids", self.user_ids(args.users).await?)
            .build();
        let page: Page<LeavePeriod> = self.client().list("leavesPeriods.list", &body).await?;
        ok(Listing::new(page.count, page.data))
    }

    /// Read one leave period by identifier: its days, its half days, its reason.
    #[rmcp::tool(annotations(
        title = "Get a leave period",
        read_only_hint = true,
        open_world_hint = true
    ))]
    pub async fn get_leave_period(
        &self,
        Parameters(args): Parameters<LeaveRefArgs>,
    ) -> std::result::Result<Json<LeavePeriod>, McpError> {
        let leave: LeavePeriod = self
            .client()
            .call("leavesPeriods.get", &Body::new().set("id", args.id).build())
            .await?;
        ok(leave)
    }

    /// Declare a leave period (days off) for a user, the current one by
    /// default. Use it for holidays and absences; use update_leave_period to
    /// move one and list_leave_periods to check existing ones first. Half days
    /// are expressed with start_type and end_type: a single afternoon off is
    /// the same day twice, pm to pm. Gryzzly refuses a leave over days that
    /// already carry time unless delete_declarations is true, which deletes
    /// that time irreversibly.
    #[rmcp::tool(annotations(
        title = "Create a leave period",
        read_only_hint = false,
        destructive_hint = false,
        idempotent_hint = false,
        open_world_hint = true
    ))]
    pub async fn create_leave_period(
        &self,
        Parameters(args): Parameters<CreateLeaveArgs>,
    ) -> std::result::Result<Json<LeavePeriod>, McpError> {
        let user = self.directory().user(args.user.as_deref()).await?;
        let start_at = date(&args.start_at)?;
        let end_at = opt_date(args.end_at.as_deref())?.unwrap_or_else(|| start_at.clone());
        if end_at < start_at {
            return Err(Error::invalid("the leave ends before it starts").into());
        }
        let body = Body::new()
            .set("user_id", user.id)
            .set("start_at", start_at)
            .set("end_at", end_at)
            .set(
                "start_type",
                args.start_type.unwrap_or(DayPart::Full).as_str(),
            )
            .set("end_type", args.end_type.unwrap_or(DayPart::Full).as_str())
            .set_opt("description", args.description)
            .set_opt("delete_declaration", args.delete_declarations)
            .build();
        let leave: LeavePeriod = self.client().call("leavesPeriods.create", &body).await?;
        ok(leave)
    }

    /// Change a leave period: move it, shorten it, turn a full day into a half
    /// one.
    #[rmcp::tool(annotations(
        title = "Update a leave period",
        read_only_hint = false,
        destructive_hint = false,
        idempotent_hint = true,
        open_world_hint = true
    ))]
    pub async fn update_leave_period(
        &self,
        Parameters(args): Parameters<UpdateLeaveArgs>,
    ) -> std::result::Result<Json<LeavePeriod>, McpError> {
        let body = Body::new()
            .set("id", args.id)
            .set_opt("start_at", opt_date(args.start_at.as_deref())?)
            .set_opt("end_at", opt_date(args.end_at.as_deref())?)
            .set_opt("start_type", args.start_type.map(DayPart::as_str))
            .set_opt("end_type", args.end_type.map(DayPart::as_str))
            .set_opt("description", args.description)
            .set_opt("delete_declaration", args.delete_declarations)
            .build();
        let leave: LeavePeriod = self.client().call("leavesPeriods.update", &body).await?;
        ok(leave)
    }

    /// Delete a leave period, which frees its days for declarations again.
    #[rmcp::tool(annotations(
        title = "Delete a leave period",
        read_only_hint = false,
        destructive_hint = true,
        idempotent_hint = true,
        open_world_hint = true
    ))]
    pub async fn delete_leave_period(
        &self,
        Parameters(args): Parameters<LeaveRefArgs>,
    ) -> std::result::Result<Json<Deleted>, McpError> {
        require_confirmation(args.confirm.unwrap_or(false), "this leave period")?;
        let _: serde_json::Value = self
            .client()
            .call(
                "leavesPeriods.delete",
                &Body::new().set("id", args.id.clone()).build(),
            )
            .await?;
        ok(Deleted::new("leave period", args.id))
    }

    /// Import leave periods from a CSV or an XLSX. The content can be written
    /// inline, or read from a path **on the machine running this server**. The
    /// report names every line Gryzzly refused.
    #[rmcp::tool(annotations(
        title = "Import leave periods",
        read_only_hint = false,
        destructive_hint = false,
        idempotent_hint = false,
        open_world_hint = true
    ))]
    pub async fn import_leave_periods(
        &self,
        Parameters(args): Parameters<ImportLeavesArgs>,
    ) -> std::result::Result<Json<ImportReport>, McpError> {
        let (bytes, format) = match (args.content, args.file_path) {
            (Some(content), None) => (
                content.into_bytes(),
                args.format.unwrap_or(ImportFormat::Csv),
            ),
            (None, Some(path)) => {
                let inferred = if path.to_lowercase().ends_with(".xlsx") {
                    ImportFormat::Xlsx
                } else {
                    ImportFormat::Csv
                };
                let bytes = tokio::fs::read(&path)
                    .await
                    .map_err(|source| Error::Io { path, source })?;
                (bytes, args.format.unwrap_or(inferred))
            }
            (Some(_), Some(_)) => {
                return Err(Error::invalid("pass content or file_path, not both").into());
            }
            (None, None) => {
                return Err(Error::invalid("pass the file as content or as file_path").into());
            }
        };
        if bytes.is_empty() {
            return Err(Error::invalid("the file is empty").into());
        }
        let report: ImportReport = self
            .client()
            .upload("leavesPeriods.import", format.content_type(), bytes)
            .await?;
        ok(report)
    }
}
