//! The two export endpoints.
//!
//! Both are `GET` with query parameters, and both authenticate a *browser
//! session* rather than an API key: called with a key, Gryzzly answers 500 with
//! `no cookie`. They are exposed anyway, because the coverage promise is the
//! whole API and because Gryzzly may fix it; the error explains the situation
//! and points at `list_time_entries`, which reads the same data.

use rmcp::{ErrorData as McpError, Json, handler::server::wrapper::Parameters};
use serde::{Deserialize, Serialize};

use crate::{
    dates,
    error::Error,
    server::GryzzlyServer,
    tools::{ok, opt_date},
};

/// The file formats the exports offer.
#[derive(Debug, Clone, Copy, Deserialize, Serialize, schemars::JsonSchema)]
#[serde(rename_all = "lowercase")]
pub enum ExportFormat {
    /// Comma-separated values.
    Csv,
    /// An Excel workbook.
    Xlsx,
}

/// What an export answers with.
#[derive(Debug, Clone, Serialize, schemars::JsonSchema)]
pub struct Export {
    /// The file's media type, as Gryzzly labelled it.
    pub content_type: String,
    /// How many bytes came back.
    pub bytes: usize,
    /// The file itself, when it is text and small enough to read here.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub text: Option<String>,
    /// Where the file was written, when `save_to` was given.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub saved_to: Option<String>,
    /// Set when the file was too large to inline.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub note: Option<String>,
}

/// How much of a text export is returned inline.
const MAX_INLINE_BYTES: usize = 200_000;

/// Arguments of `export_projects`.
#[derive(Debug, Clone, Default, Deserialize, schemars::JsonSchema)]
pub struct ExportProjectsArgs {
    /// First day of the period.
    pub from: Option<String>,
    /// Last day of the period.
    pub to: Option<String>,
    /// The projects to export, by name, code or id.
    pub projects: Option<Vec<String>>,
    /// The file format. Defaults to `csv`.
    pub format: Option<ExportFormat>,
    /// A path on the machine running this server to write the file to.
    pub save_to: Option<String>,
}

/// Arguments of `export_times_and_leaves`.
#[derive(Debug, Clone, Default, Deserialize, schemars::JsonSchema)]
pub struct ExportTimesArgs {
    /// First day of the period.
    pub from: Option<String>,
    /// Last day of the period.
    pub to: Option<String>,
    /// The file format. Defaults to `csv`.
    pub format: Option<ExportFormat>,
    /// A path on the machine running this server to write the file to.
    pub save_to: Option<String>,
}

#[allow(missing_docs, reason = "the router function is generated by the macro")]
#[rmcp::tool_router(router = exports_router, vis = "pub")]
impl GryzzlyServer {
    /// Download Gryzzly's project export, as CSV or XLSX. Upstream this
    /// endpoint wants a browser session, so with an API key it usually fails
    /// with an explanation rather than a file.
    #[rmcp::tool(annotations(
        title = "Export projects",
        read_only_hint = true,
        open_world_hint = true
    ))]
    pub async fn export_projects(
        &self,
        Parameters(args): Parameters<ExportProjectsArgs>,
    ) -> std::result::Result<Json<Export>, McpError> {
        let mut query: Vec<(&str, String)> = Vec::new();
        if let Some(from) = opt_date(args.from.as_deref())? {
            query.push(("from", from));
        }
        if let Some(to) = opt_date(args.to.as_deref())? {
            query.push(("to", to));
        }
        if let Some(projects) = args.projects {
            let mut ids = Vec::with_capacity(projects.len());
            for needle in &projects {
                ids.push(self.directory().project(needle).await?.id);
            }
            query.push(("project_ids", ids.join(",")));
        }
        query.push((
            "type",
            match args.format.unwrap_or(ExportFormat::Csv) {
                ExportFormat::Csv => "csv".to_owned(),
                ExportFormat::Xlsx => "xlsx".to_owned(),
            },
        ));
        let (bytes, content_type) = self.client().download("projects.export", &query).await?;
        ok(finish(bytes, content_type, args.save_to).await?)
    }

    /// Download Gryzzly's declarations-and-leaves export, as CSV or XLSX. Same
    /// upstream limitation as `export_projects`.
    #[rmcp::tool(annotations(
        title = "Export times and leaves",
        read_only_hint = true,
        open_world_hint = true
    ))]
    pub async fn export_times_and_leaves(
        &self,
        Parameters(args): Parameters<ExportTimesArgs>,
    ) -> std::result::Result<Json<Export>, McpError> {
        let (from, to) = match (args.from.as_deref(), args.to.as_deref()) {
            (None, None) => {
                let (monday, sunday) = dates::parse_week("this week")?;
                (dates::api_date(monday), dates::api_date(sunday))
            }
            (from, to) => (
                opt_date(from)?.unwrap_or_else(|| dates::api_date(dates::today())),
                opt_date(to)?.unwrap_or_else(|| dates::api_date(dates::today())),
            ),
        };
        // The upstream `type` parameter is an integer enum here, not a word.
        let format = match args.format.unwrap_or(ExportFormat::Csv) {
            ExportFormat::Csv => "0",
            ExportFormat::Xlsx => "1",
        };
        let query = vec![("from", from), ("to", to), ("type", format.to_owned())];
        let (bytes, content_type) = self
            .client()
            .download("timesAndLeaves.export", &query)
            .await?;
        ok(finish(bytes, content_type, args.save_to).await?)
    }
}

/// Turn the downloaded bytes into something a client can use.
async fn finish(
    bytes: Vec<u8>,
    content_type: String,
    save_to: Option<String>,
) -> std::result::Result<Export, Error> {
    let size = bytes.len();
    let written = match save_to {
        Some(path) => {
            tokio::fs::write(&path, &bytes)
                .await
                .map_err(|source| Error::Io {
                    path: path.clone(),
                    source,
                })?;
            Some(path)
        }
        None => None,
    };
    let textual = content_type.starts_with("text/")
        || content_type.contains("csv")
        || content_type.contains("json");
    let (text, note) = if textual && size <= MAX_INLINE_BYTES {
        (Some(String::from_utf8_lossy(&bytes).into_owned()), None)
    } else if textual {
        (
            None,
            Some(format!(
                "{size} bytes of text, too large to inline: pass save_to to write it to a file"
            )),
        )
    } else {
        (
            None,
            Some(format!(
                "{size} bytes of {content_type}: pass save_to to write it to a file"
            )),
        )
    };
    Ok(Export {
        content_type,
        bytes: size,
        text,
        saved_to: written,
        note,
    })
}
