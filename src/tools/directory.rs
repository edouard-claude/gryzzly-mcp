//! The directory: users, customers, and the two taxonomies Gryzzly hangs on
//! them, groups and tags.
//!
//! Tags and groups are read-only in the API, so they are read-only here.

use rmcp::{ErrorData as McpError, Json, handler::server::wrapper::Parameters};
use serde::{Deserialize, Serialize};

use crate::{
    model::{Customer, Group, Groupset, Page, Tag, Tagset, User},
    server::GryzzlyServer,
    tools::{Body, Deleted, Listing, PageArgs, ok, require_confirmation},
};

/// What a user is allowed to do in Gryzzly.
#[derive(Debug, Clone, Copy, Deserialize, Serialize, schemars::JsonSchema)]
#[serde(rename_all = "lowercase")]
pub enum Role {
    /// Declares their own time.
    Contributor,
    /// Declares time and reads more.
    Collaborator,
    /// Manages projects and people.
    Manager,
    /// Reads across the organisation.
    Director,
    /// Everything, including the API keys.
    Admin,
}

impl Role {
    fn as_str(self) -> &'static str {
        match self {
            Self::Contributor => "contributor",
            Self::Collaborator => "collaborator",
            Self::Manager => "manager",
            Self::Director => "director",
            Self::Admin => "admin",
        }
    }
}

/// Arguments of `list_users`.
#[derive(Debug, Clone, Default, Deserialize, schemars::JsonSchema)]
pub struct ListUsersArgs {
    /// Keep only users whose name or email contains this text.
    pub query: Option<String>,
    /// Include users who have been disabled. Defaults to false.
    pub include_disabled: Option<bool>,
    /// Pagination.
    #[serde(flatten)]
    pub page: PageArgs,
}

/// Arguments of `get_user`.
#[derive(Debug, Clone, Deserialize, schemars::JsonSchema)]
pub struct UserRefArgs {
    /// The user, by name, email, id, or `me`.
    pub user: String,
}

/// Arguments of `invite_user`.
#[derive(Debug, Clone, Deserialize, schemars::JsonSchema)]
pub struct InviteUserArgs {
    /// The email address to invite. Gryzzly sends the invitation itself.
    pub email: String,
    /// The role to grant. Defaults to `contributor`.
    pub role: Option<Role>,
    /// Group identifiers to put the new user in.
    pub group_ids: Option<Vec<String>>,
}

/// Arguments of `list_customers`.
#[derive(Debug, Clone, Default, Deserialize, schemars::JsonSchema)]
pub struct ListCustomersArgs {
    /// Keep only customers whose name contains this text.
    pub query: Option<String>,
    /// Keep only active, or only inactive, customers.
    pub is_active: Option<bool>,
    /// Keep only customers managed by these people, by name, email or id.
    pub managers: Option<Vec<String>>,
    /// Pagination.
    #[serde(flatten)]
    pub page: PageArgs,
}

/// Arguments of `get_customer` and `delete_customer`.
#[derive(Debug, Clone, Deserialize, schemars::JsonSchema)]
pub struct CustomerRefArgs {
    /// The customer, by name or id.
    pub customer: String,
    /// Must be `true` to delete. Ignored when reading.
    pub confirm: Option<bool>,
}

/// Arguments of `create_customer`.
#[derive(Debug, Clone, Deserialize, schemars::JsonSchema)]
pub struct CreateCustomerArgs {
    /// The customer's name.
    pub name: String,
    /// The managers, by name, email or id.
    pub managers: Option<Vec<String>>,
}

/// Arguments of `update_customer`.
#[derive(Debug, Clone, Deserialize, schemars::JsonSchema)]
pub struct UpdateCustomerArgs {
    /// The customer to change, by name or id.
    pub customer: String,
    /// A new name. Gryzzly requires one on every update; the current one is
    /// sent when this is absent.
    pub name: Option<String>,
    /// Whether the customer is active.
    pub is_active: Option<bool>,
    /// The managers, by name, email or id. Replaces the current list.
    pub managers: Option<Vec<String>>,
}

/// Arguments of the group and tag listings.
#[derive(Debug, Clone, Default, Deserialize, schemars::JsonSchema)]
pub struct TaxonomyArgs {
    /// Keep only these identifiers.
    pub ids: Option<Vec<String>>,
    /// Keep only members of these sets, by identifier.
    pub set_ids: Option<Vec<String>>,
    /// Keep only entries whose name contains this text.
    pub query: Option<String>,
    /// Pagination.
    #[serde(flatten)]
    pub page: PageArgs,
}

/// Arguments of a tool that reads one object by identifier.
#[derive(Debug, Clone, Deserialize, schemars::JsonSchema)]
pub struct IdArgs {
    /// The object's identifier.
    pub id: String,
}

#[allow(missing_docs, reason = "the router function is generated by the macro")]
#[rmcp::tool_router(router = directory_router, vis = "pub")]
impl GryzzlyServer {
    /// List the users this API key can see, which is the whole team. Disabled
    /// users are left out unless asked for.
    #[rmcp::tool(annotations(title = "List users", read_only_hint = true, open_world_hint = true))]
    pub async fn list_users(
        &self,
        Parameters(args): Parameters<ListUsersArgs>,
    ) -> std::result::Result<Json<Listing<User>>, McpError> {
        let page: Page<User> = self
            .client()
            .list("users.list", &Body::new().paged(&args.page).build())
            .await?;
        let upstream = page.data.len();
        let query = args.query.as_deref().map(str::to_lowercase);
        let include_disabled = args.include_disabled.unwrap_or(false);
        let items: Vec<User> = page
            .data
            .into_iter()
            .filter(|u| {
                include_disabled || (u.disabled_at.is_none() && u.is_disabled != Some(true))
            })
            .filter(|u| {
                query.as_ref().is_none_or(|needle| {
                    u.label().to_lowercase().contains(needle)
                        || u.email
                            .as_deref()
                            .is_some_and(|e| e.to_lowercase().contains(needle))
                })
            })
            .collect();
        ok(Listing::filtered(page.count, upstream, items))
    }

    /// Read one user: their role, their groups, the date their times are
    /// approved until, and their rates when the plan exposes them.
    #[rmcp::tool(annotations(title = "Get a user", read_only_hint = true, open_world_hint = true))]
    pub async fn get_user(
        &self,
        Parameters(args): Parameters<UserRefArgs>,
    ) -> std::result::Result<Json<User>, McpError> {
        ok(self.directory().user(Some(&args.user)).await?)
    }

    /// List tagsets, the families tags belong to (a tagset holds tags used to
    /// label projects and tasks). Use it before list_tags to see which tag
    /// families exist; use get_tagset for one tagset. Read-only, and read-only
    /// upstream too: tagsets are managed in the Gryzzly web app. An empty
    /// result is an empty list.
    #[rmcp::tool(annotations(
        title = "Invite a user",
        read_only_hint = false,
        destructive_hint = false,
        idempotent_hint = false,
        open_world_hint = true
    ))]
    pub async fn invite_user(
        &self,
        Parameters(args): Parameters<InviteUserArgs>,
    ) -> std::result::Result<Json<User>, McpError> {
        let email = args.email.trim();
        if !email.contains('@') || email.len() < 5 {
            return Err(
                crate::error::Error::invalid(format!("{email:?} is not an email address")).into(),
            );
        }
        let body = Body::new()
            .set("email", email)
            .set("role", args.role.unwrap_or(Role::Contributor).as_str())
            .set_list("group_ids", args.group_ids)
            .build();
        let user: User = self.client().call("users.invite", &body).await?;
        self.directory().invalidate_users().await;
        ok(user)
    }

    /// List customers, the entities projects are billed to.
    #[rmcp::tool(annotations(
        title = "List customers",
        read_only_hint = true,
        open_world_hint = true
    ))]
    pub async fn list_customers(
        &self,
        Parameters(args): Parameters<ListCustomersArgs>,
    ) -> std::result::Result<Json<Listing<Customer>>, McpError> {
        let body = Body::new()
            .paged(&args.page)
            .set_opt("is_active", args.is_active)
            .set_list("manager_ids", self.user_ids(args.managers).await?)
            .build();
        let page: Page<Customer> = self.client().list("customers.list", &body).await?;
        let upstream = page.data.len();
        let query = args.query.as_deref().map(str::to_lowercase);
        let items: Vec<Customer> = page
            .data
            .into_iter()
            .filter(|c| {
                query.as_ref().is_none_or(|needle| {
                    c.name
                        .as_deref()
                        .is_some_and(|n| n.to_lowercase().contains(needle))
                })
            })
            .collect();
        ok(Listing::filtered(page.count, upstream, items))
    }

    /// Read one customer: whether it is active, and who manages it.
    #[rmcp::tool(annotations(
        title = "Get a customer",
        read_only_hint = true,
        open_world_hint = true
    ))]
    pub async fn get_customer(
        &self,
        Parameters(args): Parameters<CustomerRefArgs>,
    ) -> std::result::Result<Json<Customer>, McpError> {
        ok(self.directory().customer(&args.customer).await?)
    }

    /// Create a customer, the entity projects are attached to and billed for.
    /// Managers can be named rather than identified.
    #[rmcp::tool(annotations(
        title = "Create a customer",
        read_only_hint = false,
        destructive_hint = false,
        idempotent_hint = false,
        open_world_hint = true
    ))]
    pub async fn create_customer(
        &self,
        Parameters(args): Parameters<CreateCustomerArgs>,
    ) -> std::result::Result<Json<Customer>, McpError> {
        let body = Body::new()
            .set("name", args.name)
            .set_list("managers", self.user_ids(args.managers).await?)
            .build();
        let customer: Customer = self.client().call("customers.create", &body).await?;
        self.directory().invalidate_customers().await;
        ok(customer)
    }

    /// Change a customer: rename it, deactivate it, change its managers.
    #[rmcp::tool(annotations(
        title = "Update a customer",
        read_only_hint = false,
        destructive_hint = false,
        idempotent_hint = true,
        open_world_hint = true
    ))]
    pub async fn update_customer(
        &self,
        Parameters(args): Parameters<UpdateCustomerArgs>,
    ) -> std::result::Result<Json<Customer>, McpError> {
        let current = self.directory().customer(&args.customer).await?;
        let body = Body::new()
            .set("id", current.id.clone())
            .set(
                "name",
                args.name
                    .or_else(|| current.name.clone())
                    .unwrap_or_else(|| current.id.clone()),
            )
            .set_opt("is_active", args.is_active)
            .set_list("managers", self.user_ids(args.managers).await?)
            .build();
        let customer: Customer = self.client().call("customers.update", &body).await?;
        self.directory().invalidate_customers().await;
        ok(customer)
    }

    /// Delete a customer. Gryzzly refuses while projects are attached to it.
    #[rmcp::tool(annotations(
        title = "Delete a customer",
        read_only_hint = false,
        destructive_hint = true,
        idempotent_hint = true,
        open_world_hint = true
    ))]
    pub async fn delete_customer(
        &self,
        Parameters(args): Parameters<CustomerRefArgs>,
    ) -> std::result::Result<Json<Deleted>, McpError> {
        let customer = self.directory().customer(&args.customer).await?;
        require_confirmation(
            args.confirm.unwrap_or(false),
            &format!(
                "customer {:?}",
                customer.name.as_deref().unwrap_or(&customer.id)
            ),
        )?;
        let _: serde_json::Value = self
            .client()
            .call(
                "customers.delete",
                &Body::new().set("id", customer.id.clone()).build(),
            )
            .await?;
        self.directory().invalidate_customers().await;
        ok(Deleted::new("customer", customer.id))
    }

    /// List groups, the user groupings Gryzzly assigns projects and rates to.
    /// Read-only upstream: groups are managed in the Gryzzly interface.
    #[rmcp::tool(annotations(
        title = "List groups",
        read_only_hint = true,
        open_world_hint = true
    ))]
    pub async fn list_groups(
        &self,
        Parameters(args): Parameters<TaxonomyArgs>,
    ) -> std::result::Result<Json<Listing<Group>>, McpError> {
        let body = Body::new()
            .paged(&args.page)
            .set_list("group_ids", args.ids)
            .set_list("groupset_ids", args.set_ids)
            .build();
        let page: Page<Group> = self.client().list("groups.list", &body).await?;
        let upstream = page.data.len();
        let items = filter_named(page.data, args.query.as_deref(), |g| g.name.as_deref());
        ok(Listing::filtered(page.count, upstream, items))
    }

    /// Read one group by identifier: its name, its groupset, its manager.
    #[rmcp::tool(annotations(
        title = "Get a group",
        read_only_hint = true,
        open_world_hint = true
    ))]
    pub async fn get_group(
        &self,
        Parameters(args): Parameters<IdArgs>,
    ) -> std::result::Result<Json<Group>, McpError> {
        let group: Group = self
            .client()
            .call("groups.get", &Body::new().set("id", args.id).build())
            .await?;
        ok(group)
    }

    /// List groupsets, the sets groups belong to. Read-only upstream.
    #[rmcp::tool(annotations(
        title = "List groupsets",
        read_only_hint = true,
        open_world_hint = true
    ))]
    pub async fn list_groupsets(
        &self,
        Parameters(args): Parameters<TaxonomyArgs>,
    ) -> std::result::Result<Json<Listing<Groupset>>, McpError> {
        let body = Body::new()
            .paged(&args.page)
            .set_list("groupset_ids", args.ids.or(args.set_ids))
            .build();
        let page: Page<Groupset> = self.client().list("groupsets.list", &body).await?;
        let upstream = page.data.len();
        let items = filter_named(page.data, args.query.as_deref(), |g| g.name.as_deref());
        ok(Listing::filtered(page.count, upstream, items))
    }

    /// Read one groupset by identifier, and whether its groups are exclusive.
    #[rmcp::tool(annotations(
        title = "Get a groupset",
        read_only_hint = true,
        open_world_hint = true
    ))]
    pub async fn get_groupset(
        &self,
        Parameters(args): Parameters<IdArgs>,
    ) -> std::result::Result<Json<Groupset>, McpError> {
        let groupset: Groupset = self
            .client()
            .call("groupsets.get", &Body::new().set("id", args.id).build())
            .await?;
        ok(groupset)
    }

    /// List tags, which projects and tasks are labelled with. Read-only
    /// upstream: tags are managed in the Gryzzly interface.
    #[rmcp::tool(annotations(title = "List tags", read_only_hint = true, open_world_hint = true))]
    pub async fn list_tags(
        &self,
        Parameters(args): Parameters<TaxonomyArgs>,
    ) -> std::result::Result<Json<Listing<Tag>>, McpError> {
        let body = Body::new()
            .paged(&args.page)
            .set_list("tag_ids", args.ids)
            .set_list("tagset_ids", args.set_ids)
            .build();
        let page: Page<Tag> = self.client().list("tags.list", &body).await?;
        let upstream = page.data.len();
        let items = filter_named(page.data, args.query.as_deref(), |t| t.name.as_deref());
        ok(Listing::filtered(page.count, upstream, items))
    }

    /// Read one tag by identifier: its name and the tagset it belongs to.
    #[rmcp::tool(annotations(title = "Get a tag", read_only_hint = true, open_world_hint = true))]
    pub async fn get_tag(
        &self,
        Parameters(args): Parameters<IdArgs>,
    ) -> std::result::Result<Json<Tag>, McpError> {
        let tag: Tag = self
            .client()
            .call("tags.get", &Body::new().set("id", args.id).build())
            .await?;
        ok(tag)
    }

    /// List tagsets, the sets tags belong to. Read-only upstream.
    #[rmcp::tool(annotations(
        title = "List tagsets",
        read_only_hint = true,
        open_world_hint = true
    ))]
    pub async fn list_tagsets(
        &self,
        Parameters(args): Parameters<TaxonomyArgs>,
    ) -> std::result::Result<Json<Listing<Tagset>>, McpError> {
        let body = Body::new()
            .paged(&args.page)
            .set_list("tagset_ids", args.ids.or(args.set_ids))
            .build();
        let page: Page<Tagset> = self.client().list("tagsets.list", &body).await?;
        let upstream = page.data.len();
        let items = filter_named(page.data, args.query.as_deref(), |t| t.name.as_deref());
        ok(Listing::filtered(page.count, upstream, items))
    }

    /// Read one tagset by identifier, and whether its tags are exclusive.
    #[rmcp::tool(annotations(
        title = "Get a tagset",
        read_only_hint = true,
        open_world_hint = true
    ))]
    pub async fn get_tagset(
        &self,
        Parameters(args): Parameters<IdArgs>,
    ) -> std::result::Result<Json<Tagset>, McpError> {
        let tagset: Tagset = self
            .client()
            .call("tagsets.get", &Body::new().set("id", args.id).build())
            .await?;
        ok(tagset)
    }
}

/// Keep the objects whose name contains `query`.
fn filter_named<T>(
    items: Vec<T>,
    query: Option<&str>,
    name_of: impl Fn(&T) -> Option<&str>,
) -> Vec<T> {
    let Some(needle) = query.map(str::to_lowercase) else {
        return items;
    };
    items
        .into_iter()
        .filter(|item| name_of(item).is_some_and(|name| name.to_lowercase().contains(&needle)))
        .collect()
}
