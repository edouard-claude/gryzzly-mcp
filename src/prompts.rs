//! MCP prompts: the three workflows people actually run.
//!
//! A prompt here is a script, not a personality. Each one names the tools to
//! call, in order, and where to stop and ask. The rule they all share: read
//! before writing, and never invent time.

use rmcp::{
    ErrorData as McpError,
    handler::server::{router::prompt::PromptRouter, wrapper::Parameters},
    model::{PromptMessage, Role},
};
use serde::Deserialize;

use crate::server::GryzzlyServer;

/// Arguments of `fill_my_week`.
#[derive(Debug, Clone, Default, Deserialize, schemars::JsonSchema)]
pub struct WeekArgs {
    /// The week to work on: `this week` (the default), `last week`, `2026-W38`.
    pub week: Option<String>,
    /// Hours expected on a working day. Defaults to 7.
    pub hours_per_day: Option<f64>,
}

/// Arguments of `weekly_review`.
#[derive(Debug, Clone, Default, Deserialize, schemars::JsonSchema)]
pub struct ReviewArgs {
    /// The week to report on. Defaults to last week.
    pub week: Option<String>,
}

/// Arguments of `catch_up_timesheet`.
#[derive(Debug, Clone, Default, Deserialize, schemars::JsonSchema)]
pub struct CatchUpArgs {
    /// First day to look at. Defaults to four weeks ago.
    pub from: Option<String>,
    /// Last day to look at. Defaults to yesterday.
    pub to: Option<String>,
}

/// The prompt router this server exposes.
pub fn router() -> PromptRouter<GryzzlyServer> {
    GryzzlyServer::prompt_router()
}

#[allow(missing_docs, reason = "the router function is generated by the macro")]
#[rmcp::prompt_router]
impl GryzzlyServer {
    /// Fill a week's timesheet: read what is already there, propose what is
    /// missing from real evidence, get it approved, then write it in one call.
    #[rmcp::prompt(name = "fill_my_week")]
    pub async fn fill_my_week_prompt(
        &self,
        Parameters(args): Parameters<WeekArgs>,
    ) -> std::result::Result<Vec<PromptMessage>, McpError> {
        let week = args.week.unwrap_or_else(|| "this week".to_owned());
        let hours = args.hours_per_day.unwrap_or(7.0);
        let text = format!(
            "Fill my Gryzzly timesheet for {week}, expecting about {hours} hours per working day.\n\
             \n\
             Work in this order, and do not skip the third step:\n\
             1. `whoami`, then `timesheet` with week = \"{week}\" and expected_hours_per_day = {hours}. \
                Tell me what is already logged and which working days fall short.\n\
             2. `list_projects` and, for the plausible ones, `list_tasks`, so the names you propose exist. \
                If I have logged time in earlier weeks, `list_time_entries` over the last three weeks \
                shows how I usually split my days: reuse those tasks and descriptions rather than inventing categories.\n\
             3. Show me a table of what you propose to add: day, project, task, duration, description. \
                Stop there and wait for my explicit agreement. Do not write anything yet.\n\
             4. Once I agree, write it with a single `log_time_bulk` call, then read the week back with \
                `timesheet` and show me the totals.\n\
             \n\
             Rules: never log time on a day that already has some unless I asked you to add to it. \
             Never guess what I worked on: if the evidence is thin, say so and ask. \
             Leave weekends alone unless I say otherwise.\n\
             Descriptions are what a human reads in six months: write them accordingly."
        );
        Ok(vec![PromptMessage::new_text(Role::User, text)])
    }

    /// Report on a week of declared time: totals, split per project, and what
    /// looks wrong. Reads only, writes nothing.
    #[rmcp::prompt(name = "weekly_review")]
    pub async fn weekly_review_prompt(
        &self,
        Parameters(args): Parameters<ReviewArgs>,
    ) -> std::result::Result<Vec<PromptMessage>, McpError> {
        let week = args.week.unwrap_or_else(|| "last week".to_owned());
        let text = format!(
            "Review my Gryzzly time for {week}. This is a read-only exercise: do not create, \
             change or delete anything.\n\
             \n\
             1. `timesheet` with week = \"{week}\" for the totals, the per-project split and the days that fall short.\n\
             2. `list_time_entries` for the same week to see the entries themselves.\n\
             3. `list_leave_periods` for the same week, so a day off is not read as a missing day.\n\
             \n\
             Then tell me, in a few lines: how much was declared, how it splits across projects, \
             which days look wrong (empty working days, days over ten hours, duplicate-looking entries), \
             and one sentence on what changed against the previous week if you can see it."
        );
        Ok(vec![PromptMessage::new_text(Role::User, text)])
    }

    /// Find the working days left empty over a period and close the gaps, one
    /// approval at a time.
    #[rmcp::prompt(name = "catch_up_timesheet")]
    pub async fn catch_up_timesheet_prompt(
        &self,
        Parameters(args): Parameters<CatchUpArgs>,
    ) -> std::result::Result<Vec<PromptMessage>, McpError> {
        let from = args.from.unwrap_or_else(|| {
            crate::dates::api_date(crate::dates::today() - chrono::Duration::weeks(4))
        });
        let to = args.to.unwrap_or_else(|| {
            crate::dates::api_date(crate::dates::today() - chrono::Duration::days(1))
        });
        let text = format!(
            "My Gryzzly timesheet has holes between {from} and {to}. Close them, carefully.\n\
             \n\
             1. `timesheet` with from = \"{from}\" and to = \"{to}\" to list the working days below the expected hours.\n\
             2. `list_leave_periods` over the same period: a day of leave is not a hole.\n\
             3. `list_time_entries` over the period to see what I usually work on and how I describe it.\n\
             4. Present the remaining holes week by week, with a proposal per day based on what \
                surrounds it. Ask me to confirm one week at a time, and write each approved week with \
                one `log_time_bulk` call.\n\
             \n\
             Never fill a day you have no evidence for: list it as unexplained and let me answer. \
             Days already carrying time are not holes."
        );
        Ok(vec![PromptMessage::new_text(Role::User, text)])
    }
}

#[cfg(test)]
mod tests {
    #![allow(
        clippy::unwrap_used,
        clippy::expect_used,
        clippy::panic,
        reason = "a test that cannot fail loudly is not a test"
    )]
    use crate::config::Config;

    #[test]
    fn the_three_workflows_are_exposed_and_described() {
        let _ = Config::from_getter(|_| None);
        let router = super::router();
        let prompts = router.list_all();
        let names: Vec<String> = prompts.iter().map(|p| p.name.clone()).collect();
        assert_eq!(prompts.len(), 3, "{names:?}");
        assert!(names.contains(&"fill_my_week".to_owned()));
        assert!(names.contains(&"weekly_review".to_owned()));
        assert!(names.contains(&"catch_up_timesheet".to_owned()));
        for prompt in prompts {
            let description = prompt
                .description
                .as_deref()
                .unwrap_or_else(|| panic!("{} has no description", prompt.name));
            assert!(description.len() > 30, "{}: {description:?}", prompt.name);
        }
    }
}
